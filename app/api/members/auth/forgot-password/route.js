// app/api/members/auth/forgot-password/route.js
// Send a password-reset email to the member's registered email.
//   POST { memberId } → { ok }  (always, unless the request itself is invalid)
//   GET  → admin-only debug echo of the origin/env used to build the link
//
// We look up the member by ID, then use Supabase Auth to send the reset link.
// To avoid leaking account existence, every no-send path returns the same
// generic { ok: true } as a successful send; the concrete reason is logged on
// the server only.
import { NextResponse } from 'next/server'
import { createClient } from '@supabase/supabase-js'
import { createClient as createDbClient } from '@/lib/supabaseServer'
import { checkRateLimit, rateLimitResponse } from '@/lib/rateLimit'
import { validateSession } from '@/lib/validation'

export const runtime = 'nodejs'
export const dynamic = 'force-dynamic'

// Service-role client for the email send. The old anon-key call was being
// silently rejected on the hosted Supabase project (no email arrived and the
// SDK error was swallowed), so the reset email is generated by the admin
// client instead — service-role sends skip the anonymous-key rate limits.
const authServiceRole = createClient(
  process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { persistSession: false, autoRefreshToken: false } }
)

// Resolves the URL-of-origin the member's browser sees, so the reset link
// always points to a reachable page. Order:
//   1. explicit NEXT_PUBLIC_SITE_URL (must be a full http(s) URL)
//   2. request Origin header (browser origin, works behind proxies)
//   3. request Host + x-forwarded-proto headers
function resolveSiteOrigin(request) {
  const direct = (process.env.NEXT_PUBLIC_SITE_URL || '').replace(/\/+$/, '')
  if (direct && /^https?:\/\//i.test(direct)) return direct
  if (request?.headers) {
    const origin = request.headers.get('origin')
    if (origin && /^https?:\/\//i.test(origin)) return origin
    const host = request.headers.get('host')
    if (host) {
      const proto =
        request.headers.get('x-forwarded-proto') ||
        (/^(localhost|127\.)/i.test(host) ? 'http' : 'https')
      return `${proto}://${host}`
    }
  }
  if (direct) return direct // configured but unprefixed — better than nothing
  return ''
}

export async function POST(request) {
  try {
    const { memberId } = await request.json().catch(() => ({}))
    const mid = String(memberId || '').trim().toUpperCase()

    if (!mid) {
      return NextResponse.json({ error: 'Member ID is required' }, { status: 400 })
    }

    // Rate limit: 3 reset requests per member per 10 minutes
    const resetLimit = checkRateLimit('forgot-pw', mid, 3, 10 * 60 * 1000)
    if (!resetLimit.allowed) return rateLimitResponse(resetLimit.retryAfterMs)

    const siteOrigin = resolveSiteOrigin(request)

    // Look up the member's email
    const db = createDbClient()
    const { data: member, error: mErr } = await db
      .from('members')
      .select('member_id, email, auth_user_id, portal_enabled')
      .eq('member_id', mid)
      .maybeSingle()

    if (mErr) {
      console.error('[forgot-password] members lookup failed:', mErr.message)
      return NextResponse.json({ error: mErr.message }, { status: 500 })
    }
    if (
      !member ||
      member.portal_enabled === false ||
      !member.auth_user_id ||
      !member.email
    ) {
      // Unknown member / not in the portal cohort / no auth account — never
      // reveal which; the concrete reason is on the server console.
      console.warn(
        `[forgot-password] ${mid}: no reset email sent (${member ? (member.portal_enabled === false ? 'not in cohort' : member.auth_user_id ? 'missing email' : 'no auth account') : 'unknown member'})`
      )
      if (!siteOrigin && member?.email) {
        console.error(
          `[forgot-password] NOTE: NEXT_PUBLIC_SITE_URL is not set in this environment and the request had no usable Origin/Host — even valid members will get no email. Set NEXT_PUBLIC_SITE_URL.`
        )
      }
      return NextResponse.json({ ok: true })
    }

    if (!siteOrigin) {
      // Without a full origin the redirect URL would be relative and Supabase
      // rejects it, so the send would fail anyway. Log loudly.
      console.error(
        `[forgot-password] ${mid}: cannot send reset email — no resolvable site origin. Set NEXT_PUBLIC_SITE_URL in the deployed environment.`
      )
      return NextResponse.json({ ok: true })
    }

    const redirectTo = `${siteOrigin}/reset-password`

    // Send the password reset email via the Supabase admin API.
    const { error: resetError } = await authServiceRole.auth.resetPasswordForEmail(
      member.email,
      { redirectTo }
    )

    if (resetError) {
      console.error(
        `[forgot-password] reset email FAILED for ${mid} (${member.email}):`,
        JSON.stringify({
          code: resetError.code,
          status: resetError.status,
          message: resetError.message,
          redirectTo,
        })
      )
      // Still return success to avoid leaking info; the failure details are on
      // the server console. A retry (10 min apart, per rate limit) may succeed.
      return NextResponse.json({ ok: true })
    }

    console.log(
      `[forgot-password] reset email sent to ${mid} (${member.email}) → ${redirectTo}`
    )
    return NextResponse.json({ ok: true })
  } catch (e) {
    console.error('[forgot-password] unexpected error:', e.message || e)
    return NextResponse.json({ error: e.message || 'Internal server error' }, { status: 500 })
  }
}

// Admin-only debug endpoint: echoes the origin the deployed environment will
// resolve for building the reset link (does not touch Supabase).
export async function GET(request) {
  const session = await validateSession(request, 'admin')
  if (!session.valid) return NextResponse.json({ ok: false, error: 'Unauthorized' }, { status: 401 })
  return NextResponse.json({
    ok: true,
    env: {
      NEXT_PUBLIC_SITE_URL: process.env.NEXT_PUBLIC_SITE_URL || null,
      service_role_set: Boolean(process.env.SUPABASE_SERVICE_ROLE_KEY),
    },
    resolvedSiteOrigin: resolveSiteOrigin(request),
    redirectToExample: resolveSiteOrigin(request)
      ? `${resolveSiteOrigin(request)}/reset-password`
      : null,
  })
}
